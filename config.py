# ---------------------------------------------------------------------------
# 2. INTER-AGENT DATA MODELS
# ---------------------------------------------------------------------------

@dataclass
class BugReport:
    """Bug report model generated by Scout Agent."""
    bug_id: str
    file_path: str
    title: str
    description: str
    bug_type: str  # Logic, Security, ResourceLeak, TypeMismatch
    severity: str  # HIGH, MEDIUM, LOW
    suggested_reproduction: str

@dataclass
class TestReproduction:
    """Test reproduction model generated by Reproducer Agent."""
    __test__ = False  # Prevents pytest from collecting this dataclass as a test class
    bug_id: str
    test_file_path: str
    test_code: str
    initial_test_status: str  # FAILED / ERROR / PASSED
    error_output: str

@dataclass
class FixResult:
    """Fix and PR result model generated by Fixer Agent."""
    bug_id: str
    fixed_file_path: str
    patch_code: str
    final_test_status: str  # PASSED
    pr_title: str
    pr_body: str

@dataclass
class VerificationResult:
    """Security and scope verification model generated by Verifier Agent."""
    bug_id: str
    is_accepted: bool  # True if patch meets all acceptance criteria
    security_score: int  # 0 to 100
    scope_isolated: bool  # True if patch only touches intended files
    permission_expanded: bool  # True if dangerous/broad permissions were detected
    sandbox_status: str  # PASSED / FAILED / BLOCKED
    audit_notes: str

# ---------------------------------------------------------------------------
# 3. GENAI CLIENT FACTORY
# ---------------------------------------------------------------------------

def get_genai_client() -> genai.Client:
    """
    Creates a google-genai Client instance.
    Reads GEMINI_API_KEY or GOOGLE_API_KEY from environment variables.
    """
    api_key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if api_key:
        return genai.Client(api_key=api_key)
    return genai.Client(api_key="DUMMY_KEY")